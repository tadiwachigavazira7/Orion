import enum
import uuid
from datetime import datetime

from sqlalchemy import (
    CheckConstraint,
    Computed,
    DateTime,
    Enum as SAEnum,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from orion_backend.db.base import Base


class DeviceStatus(str, enum.Enum):
    ACTIVE = "ACTIVE"
    REVOKED = "REVOKED"


class EnrolledDevice(Base):
    """A PDT device trusted to run Orion. Never stores the plaintext
    enrollment credential — only an Argon2id hash (see services.credential_hasher).
    """

    __tablename__ = "enrolled_devices"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    device_id: Mapped[str] = mapped_column(String(128), unique=True, nullable=False, index=True)
    site_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("sites.id"), nullable=False
    )
    credential_hash: Mapped[str] = mapped_column(String(512), nullable=False)
    status: Mapped[DeviceStatus] = mapped_column(
        SAEnum(DeviceStatus, name="device_status", native_enum=True),
        nullable=False,
        default=DeviceStatus.ACTIVE,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )
    last_verified_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)

    site: Mapped["Site"] = relationship()


class Organization(Base):
    """A retailer organization/tenant identified by a unique organization code."""

    __tablename__ = "organizations"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    organization_code: Mapped[str] = mapped_column(
        String(128), unique=True, nullable=False, index=True
    )
    name: Mapped[str] = mapped_column(String(255), nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    sites: Mapped[list["Site"]] = relationship(back_populates="organization")


class Site(Base):
    """A retailer store/warehouse site, scoped to an organization.

    site_code is only unique within its organization (see
    uq_sites_organization_id_site_code) - the same code may be reused by
    different organizations.
    """

    __tablename__ = "sites"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    site_code: Mapped[str] = mapped_column(String(128), nullable=False)
    organization_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("organizations.id"), nullable=False
    )
    included_device_slots: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default="6"
    )
    extra_device_slots: Mapped[int] = mapped_column(
        Integer, nullable=False, server_default="0"
    )
    # Single source of truth for capacity. Generated by Postgres: read-only in
    # the ORM; re-read (refresh / lock_site) after changing either slot column.
    max_devices: Mapped[int] = mapped_column(
        Integer, Computed("included_device_slots + extra_device_slots", persisted=True)
    )
    # Argon2id hash of the per-site enrollment code. NULL => enrollment is not
    # provisioned => enrollment fails closed.
    enrollment_code_hash: Mapped[str | None] = mapped_column(String(512), nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    organization: Mapped["Organization"] = relationship(back_populates="sites")

    __table_args__ = (
        UniqueConstraint("organization_id", "site_code", name="uq_sites_organization_id_site_code"),
        CheckConstraint("extra_device_slots >= 0", name="ck_sites_extra_device_slots_nonneg"),
        CheckConstraint("included_device_slots >= 0", name="ck_sites_included_device_slots_nonneg"),
    )


class SubscriptionPlan(str, enum.Enum):
    STANDARD = "STANDARD"
    PILOT = "PILOT"


class SubscriptionStatus(str, enum.Enum):
    PENDING = "PENDING"
    ACTIVE = "ACTIVE"
    SUSPENDED = "SUSPENDED"
    EXPIRED = "EXPIRED"
    CANCELED = "CANCELED"


class Subscription(Base):
    """A site's entitlement to use Orion. Holds NO capacity (see Site.max_devices)."""

    __tablename__ = "subscriptions"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    site_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("sites.id"), nullable=False, unique=True
    )
    plan_code: Mapped[SubscriptionPlan] = mapped_column(
        SAEnum(SubscriptionPlan, name="subscription_plan", native_enum=True), nullable=False
    )
    status: Mapped[SubscriptionStatus] = mapped_column(
        SAEnum(SubscriptionStatus, name="subscription_status", native_enum=True),
        nullable=False,
        default=SubscriptionStatus.PENDING,
    )
    monthly_price_cents: Mapped[int] = mapped_column(
        Integer, nullable=False, default=40000, server_default="40000"
    )
    current_period_start: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    current_period_end: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), onupdate=func.now(), nullable=False
    )

    __table_args__ = (
        CheckConstraint("monthly_price_cents >= 0", name="ck_subscriptions_monthly_price_nonneg"),
        CheckConstraint(
            "current_period_end IS NULL OR current_period_start IS NULL "
            "OR current_period_end > current_period_start",
            name="ck_subscriptions_period_order",
        ),
        Index("ix_subscriptions_status", "status"),
    )


class AuditEvent(Base):
    """Append-only operator/system audit trail (the app only ever INSERTs).
    Never put credentials, enrollment codes or hashes in `details`."""

    __tablename__ = "audit_events"

    id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    occurred_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    actor: Mapped[str] = mapped_column(String(128), nullable=False)
    action: Mapped[str] = mapped_column(String(64), nullable=False)
    site_id: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("sites.id"), nullable=True
    )
    details: Mapped[dict] = mapped_column(
        JSONB, nullable=False, default=dict, server_default=text("'{}'::jsonb")
    )
